#ifndef __BOARD_QUEST_QRK3588_MEMORY_H
#define __BOARD_QUEST_QRK3588_MEMORY_H

#define QRK3588_DRAM_BANK0_BASE	0x0000000000000000
#define QRK3588_DRAM_BANK0_SIZE	0x00000000f0000000

#define QRK3588_DRAM_BANK1_BASE	0x00000001f0000000
#define QRK3588_DRAM_BANK1_SIZE	0x000000000fe00000

#define QRK3588_DEVICE_BASE		0x00000000f0000000
#define QRK3588_DEVICE_SIZE		0x000000000f000000

#ifdef __DTS__
#define QRK3588_DRAM_REG(base, size) \
	((base) >> 32) ((base) & 0xffffffff) \
	((size) >> 32) ((size) & 0xffffffff)

#define QRK3588_DRAM_BANK0_REG \
	QRK3588_DRAM_REG(QRK3588_DRAM_BANK0_BASE, QRK3588_DRAM_BANK0_SIZE)
#define QRK3588_DRAM_BANK1_REG \
	QRK3588_DRAM_REG(QRK3588_DRAM_BANK1_BASE, QRK3588_DRAM_BANK1_SIZE)
#endif

#endif /* __BOARD_QUEST_QRK3588_MEMORY_H */
